import sharp from 'sharp'
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const heroDirectory = path.join(root, 'src/assets/hero')
const widths = [1600, 2560, 3840]
const quality = 96
const smartSubsample = false
const imports = []
const records = []
const report = []
const hash = buffer => createHash('sha256').update(buffer).digest('hex')

for (let number = 1; number <= 6; number++) {
  const id = `hero-${String(number).padStart(2, '0')}`
  const originalPath = path.join(heroDirectory, `${id}.png`)
  const original = await readFile(originalPath)
  const metadata = await sharp(original).metadata()
  const derivatives = []

  for (const width of widths) {
    const filename = `${id}-${width}.webp`
    // Width only: preserve the full composition and original aspect ratio.
    // Sharp maps Lanczos3 to high-quality cubic interpolation when upsampling.
    const { data, info } = await sharp(original)
      .resize({ width, kernel: sharp.kernel.lanczos3 })
      .keepIccProfile()
      .webp({ quality, effort: 6, smartSubsample })
      .toBuffer({ resolveWithObject: true })
    await writeFile(path.join(heroDirectory, filename), data)
    const binding = `hero${number}_${width}`
    imports.push(`import ${binding} from '../assets/hero/${filename}'`)
    derivatives.push({
      filename, width: info.width, height: info.height, bytes: info.size,
      method: width > metadata.width ? 'upscale-cubic' : 'downscale-lanczos3',
      scale: width / metadata.width,
    })
  }

  if (hash(await readFile(originalPath)) !== hash(original)) throw new Error(`Original modified: ${id}`)
  const srcSet = widths.map(width => `\${hero${number}_${width}} ${width}w`).join(', ')
  records.push(`  '${id}': { image: hero${number}_${widths[0]}, srcSet: \`${srcSet}\`, width: ${metadata.width}, height: ${metadata.height} },`)
  report.push({
    original: { filename: `${id}.png`, width: metadata.width, height: metadata.height, bytes: original.length, sha256: hash(original) },
    sourceScaleAt1920: 1920 / metadata.width,
    derivatives,
  })
}

await mkdir(path.join(root, 'docs'), { recursive: true })
await writeFile(path.join(root, 'src/data/heroImages.generated.js'),
  `// Generated by npm run images:hero. Do not edit by hand.\n${imports.join('\n')}\n\nexport const heroImages = {\n${records.join('\n')}\n}\n`)
await writeFile(path.join(root, 'docs/hero-image-report.json'), `${JSON.stringify({
  quality, smartSubsample, effort: 6,
  encoder: `sharp ${sharp.versions.sharp} / libvips ${sharp.versions.vips}`,
  composition: 'Width-only resize; no crop, filters, sharpening, denoising or color adjustments. Input ICC profiles retained.',
  interpolation: 'Lanczos3 downsampling; cubic upsampling as defined by Sharp.',
  images: report,
}, null, 2)}\n`)
console.table(report.map(image => ({
  original: image.original.filename,
  resolution: `${image.original.width}×${image.original.height}`,
  upscaled: image.derivatives.filter(variant => variant.method === 'upscale-cubic').map(variant => variant.width).join(', ') || 'none',
  originalMB: (image.original.bytes / 1e6).toFixed(2),
  ...Object.fromEntries(image.derivatives.map(variant => [`webp${variant.width}KB`, Math.round(variant.bytes / 1000)])),
})))
