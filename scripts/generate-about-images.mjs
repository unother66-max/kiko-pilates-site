import sharp from 'sharp'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = path.join(root, 'src/assets/about/editorial')
const keys = { 1: 'studio', 2: 'equipment', 3: 'pilates', 4: 'entrance', 5: 'lounge', 7: 'ballet' }
const files = await readdir(directory)
const hash = data => createHash('sha256').update(data).digest('hex')
const imports = [], records = [], reports = []

for (const [number, key] of Object.entries(keys)) {
  const prefix = `source-${number.padStart(2, '0')}.`
  const source = files.find(file => file.startsWith(prefix))
  if (!source) throw new Error(`Missing approved photo: ${number}`)
  const original = await readFile(path.join(directory, source))
  const metadata = await sharp(original).metadata()
  const widths = [...new Set([640, 1000, 1440, 1920, 2560, 3200, metadata.width])].filter(width => width <= metadata.width).sort((a, b) => a - b)
  const variants = []
  for (const width of widths) {
    const filename = `photo-${number.padStart(2, '0')}-${width}.webp`
    const nativeWebp = metadata.format === 'webp' && width === metadata.width
    const data = nativeWebp ? original : await sharp(original)
      .resize({ width, kernel: sharp.kernel.lanczos3, withoutEnlargement: true })
      .keepIccProfile()
      .webp({ quality: 96, effort: 6, smartSubsample: false }).toBuffer()
    await writeFile(path.join(directory, filename), data)
    const info = await sharp(data).metadata()
    variants.push({ filename, width: info.width, height: info.height, bytes: data.length, sourceBytesRetained: nativeWebp })
    imports.push(`import ${key}${width} from '../assets/about/editorial/${filename}'`)
  }
  if (hash(await readFile(path.join(directory, source))) !== hash(original)) throw new Error(`Original changed: ${source}`)
  const srcSet = variants.map(variant => `\${${key}${variant.width}} ${variant.width}w`).join(', ')
  const fallback = variants.find(variant => variant.width === 1440) ?? variants.at(-1)
  records.push(`  ${key}: {\n    number: ${number}, image: ${key}${fallback.width},\n    srcSet: \`${srcSet}\`,\n    width: ${metadata.width}, height: ${metadata.height},\n  }`)
  reports.push({ number: Number(number), key, original: { filename: source, width: metadata.width, height: metadata.height, bytes: original.length, sha256: hash(original) }, variants })
}
await writeFile(path.join(root, 'src/data/aboutPhotos.generated.js'), `// Generated by node scripts/generate-about-images.mjs. ABOUT only.\n${imports.join('\n')}\n\nexport const aboutPhotos = {\n${records.join(',\n')}\n}\n`)
await writeFile(path.join(root, 'docs/about-image-report.json'), `${JSON.stringify({
  quality: 96, effort: 6, smartSubsample: false,
  treatment: 'Originals preserved. Native WebP copied byte for byte at maximum width. Other variants use Lanczos3 downscale only, with no crop, filter, sharpening, color correction or enlargement.',
  photos: reports,
}, null, 2)}\n`)
console.table(reports.map(photo => ({ number: photo.number, source: photo.original.filename, resolution: `${photo.original.width}×${photo.original.height}`, widths: photo.variants.map(v => v.width).join(', ') })))
