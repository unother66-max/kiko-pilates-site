import sharp from 'sharp'
import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = path.join(root, 'src/assets/about')
const photos = [
  { key: 'studio', original: 'original-06.png', name: 'studio', widths: [640, 1200, 1600, 2560, 3200] },
  { key: 'equipment', original: 'original-09.png', name: 'equipment', widths: [640, 1200, 1600, 2174] },
  { key: 'lounge', original: 'original-11.png', name: 'lounge', widths: [640, 1200, 1600, 2560] },
]
const hash = data => createHash('sha256').update(data).digest('hex')
const imports = []
const records = []
const reports = []

for (const photo of photos) {
  const originalPath = path.join(directory, photo.original)
  const original = await readFile(originalPath)
  const metadata = await sharp(original).metadata()
  const variants = []

  for (const width of photo.widths.filter(value => value <= metadata.width)) {
    const filename = `${photo.name}-${width}.webp`
    const { data, info } = await sharp(original)
      .resize({ width, kernel: sharp.kernel.lanczos3, withoutEnlargement: true })
      .keepIccProfile()
      .webp({ quality: 96, effort: 6, smartSubsample: false })
      .toBuffer({ resolveWithObject: true })
    await writeFile(path.join(directory, filename), data)
    variants.push({ filename, width: info.width, height: info.height, bytes: info.size })
    imports.push(`import ${photo.key}${width} from '../assets/about/${filename}'`)
  }

  if (hash(await readFile(originalPath)) !== hash(original)) throw new Error(`Original changed: ${photo.original}`)
  const srcSet = variants.map(variant => `\${${photo.key}${variant.width}} ${variant.width}w`).join(', ')
  const fallback = variants.find(variant => variant.width === 1200) ?? variants[0]
  records.push(`  ${photo.key}: {\n    image: ${photo.key}${fallback.width},\n    srcSet: \`${srcSet}\`,\n    width: ${metadata.width}, height: ${metadata.height},\n  }`)
  reports.push({ key: photo.key, original: { filename: photo.original, width: metadata.width, height: metadata.height, bytes: original.length, sha256: hash(original) }, variants })
}

await writeFile(path.join(root, 'src/data/aboutPhotos.generated.js'), `// Generated by node scripts/generate-about-images.mjs. ABOUT only.\n${imports.join('\n')}\n\nexport const aboutPhotos = {\n${records.join(',\n')}\n}\n`)
await writeFile(path.join(root, 'docs/about-image-report.json'), `${JSON.stringify({
  quality: 96, smartSubsample: false, effort: 6,
  treatment: 'Width-only Lanczos3 resize, no enlargement, no crop, original ICC retained. No filter, color adjustment, sharpening, denoise or AI generation.',
  photos: reports,
}, null, 2)}\n`)
console.table(reports.flatMap(photo => photo.variants.map(variant => ({ file: variant.filename, resolution: `${variant.width}×${variant.height}`, kB: Math.round(variant.bytes / 1000) }))))
