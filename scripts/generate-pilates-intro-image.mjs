import sharp from 'sharp'
import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = path.join(root, 'src/assets/pilates')
const originalPath = path.join(directory, 'studio-intro-01.png')
const original = await readFile(originalPath)
const metadata = await sharp(original).metadata()
const hash = buffer => createHash('sha256').update(buffer).digest('hex')
const widths = [640, 1000, 1600, 2560].filter(width => width <= metadata.width)
const variants = []

for (const width of widths) {
  const filename = `studio-intro-01-${width}.webp`
  const { data, info } = await sharp(original)
    .resize({ width, kernel: sharp.kernel.lanczos3, withoutEnlargement: true })
    .keepIccProfile()
    .webp({ quality: 96, effort: 6, smartSubsample: false })
    .toBuffer({ resolveWithObject: true })
  await writeFile(path.join(directory, filename), data)
  variants.push({ filename, width: info.width, height: info.height, bytes: info.size })
}

if (hash(await readFile(originalPath)) !== hash(original)) throw new Error('Intro original changed')
const imports = variants.map(variant => `import intro${variant.width} from '../assets/pilates/${variant.filename}'`)
const srcSet = variants.map(variant => `\${intro${variant.width}} ${variant.width}w`).join(', ')
await writeFile(path.join(root, 'src/data/pilatesIntroImage.generated.js'),
  `// Generated by node scripts/generate-pilates-intro-image.mjs. Intro-only image.\n${imports.join('\n')}\n\nexport const pilatesIntroImage = {\n  image: intro1000,\n  srcSet: \`${srcSet}\`,\n  width: ${metadata.width}, height: ${metadata.height},\n}\n`)
await writeFile(path.join(root, 'docs/pilates-intro-image-report.json'), `${JSON.stringify({
  original: { filename: 'studio-intro-01.png', width: metadata.width, height: metadata.height, bytes: original.length, sha256: hash(original) },
  quality: 96, smartSubsample: false, effort: 6,
  treatment: 'Width-only Lanczos3 downscale, original aspect ratio and ICC retained. No crop, upscale, filters, sharpening or color adjustments.',
  variants,
}, null, 2)}\n`)
console.table(variants.map(variant => ({ file: variant.filename, resolution: `${variant.width}×${variant.height}`, kB: Math.round(variant.bytes / 1000) })))
