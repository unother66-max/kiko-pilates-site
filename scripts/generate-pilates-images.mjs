import sharp from 'sharp'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = path.join(root, 'src/assets/pilates')
const images = [
  { id: 'private-01', widths: [640, 1000, 1600, 2560, 3840] },
  { id: 'duet-01', widths: [480, 800, 1254] },
  { id: 'group-01', widths: [640, 960, 1254] },
]
const imports = [], records = [], report = []
const hash = data => createHash('sha256').update(data).digest('hex')

for (const [index, image] of images.entries()) {
  const originalPath = path.join(directory, `${image.id}.png`)
  const original = await readFile(originalPath)
  const metadata = await sharp(original).metadata()
  // Every derivative comes directly from the PNG; never upscale or crop.
  const widths = image.widths.filter(width => width <= metadata.width)
  const variants = []
  for (const width of widths) {
    const filename = `${image.id}-${width}.webp`
    const { data, info } = await sharp(original)
      .resize({ width, kernel: sharp.kernel.lanczos3, withoutEnlargement: true })
      .keepIccProfile()
      .webp({ quality: 96, effort: 6, smartSubsample: false })
      .toBuffer({ resolveWithObject: true })
    await writeFile(path.join(directory, filename), data)
    const binding = `photo${index}_${width}`
    imports.push(`import ${binding} from '../assets/pilates/${filename}'`)
    variants.push({ filename, width: info.width, height: info.height, bytes: info.size, binding })
  }
  if (hash(await readFile(originalPath)) !== hash(original)) throw new Error(`Original changed: ${image.id}`)
  const defaultImage = variants.find(variant => variant.width >= 800) || variants.at(-1)
  const srcSet = variants.map(variant => `\${${variant.binding}} ${variant.width}w`).join(', ')
  records.push(`  '${image.id}': { image: ${defaultImage.binding}, srcSet: \`${srcSet}\`, width: ${metadata.width}, height: ${metadata.height} },`)
  report.push({
    original: { filename: `${image.id}.png`, width: metadata.width, height: metadata.height, bytes: original.length, sha256: hash(original) },
    variants: variants.map(({ binding: _binding, ...variant }) => variant),
  })
}

await mkdir(path.join(root, 'docs'), { recursive: true })
await writeFile(path.join(root, 'src/data/pilatesImages.generated.js'),
  `// Generated by node scripts/generate-pilates-images.mjs.\n${imports.join('\n')}\n\nexport const pilatesImages = {\n${records.join('\n')}\n}\n`)
await writeFile(path.join(root, 'docs/pilates-image-report.json'), `${JSON.stringify({
  quality: 96, smartSubsample: false, effort: 6,
  treatment: 'Width-only Lanczos3 downscale / original size. No upscale, crop, sharpening, filters, denoising or color correction. Original ICC retained.',
  encoder: `sharp ${sharp.versions.sharp} / libvips ${sharp.versions.vips}`,
  images: report,
}, null, 2)}\n`)
console.table(report.flatMap(image => image.variants.map(variant => ({
  image: variant.filename, resolution: `${variant.width}×${variant.height}`, kB: Math.round(variant.bytes / 1000),
}))))
